function renderProjects(c, ctx) {
  var list = c.projects || [];
  if (!list.length) return '';
  var flagship = list.filter(function (p) { return p.tier === 'flagship'; });
  var featured = list.filter(function (p) { return p.tier === 'featured'; });
  var compact = list.filter(function (p) { return p.tier !== 'flagship' && p.tier !== 'featured'; });
  var featuredCards = flagship.concat(featured);

  var parts = [];
  if (featuredCards.length) {
    parts.push('<h3 class="group-title">' + esc(ctx.labels.projectsFeatured || 'Selected work') + '</h3>');
    parts.push('<div class="projects-featured">');
    parts.push(featuredCards.map(function (p) { return renderFeaturedCard(p, ctx); }).join('\n'));
    parts.push('</div>');
  }
  if (compact.length) {
    parts.push('<h3 class="group-title">' + esc(ctx.labels.projectsMore || 'More experiments') + '</h3>');
    parts.push('<div class="projects-compact">');
    parts.push(compact.map(function (p) { return renderCompactRow(p, ctx); }).join('\n'));
    parts.push('</div>');
  }
  return parts.join('\n');
}

