/* ---------- Load data/content.js (single source of truth) ---------- */
function loadContent() {
  const code = read('data/content.js');
  const sandbox = { window: {}, console };
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: 'data/content.js' });
  const site = (sandbox.window && sandbox.window.SITE_CONTENT) || {};
  if (!site.en || !site.ru) {
    throw new Error('data/content.js must expose window.SITE_CONTENT = { en, ru }');
  }
  return site;
}

/* ---------- Shared helpers (mirror the previous runtime renderer) ---------- */
function esc(str) {
  return String(str == null ? '' : str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function isExternal(url) {
  return String(url).indexOf('http') === 0;
}

function chip(t) {
  return '<span class="chip">' + esc(t) + '</span>';
}

