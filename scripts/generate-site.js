function renderFeaturedCard(p, ctx) {
  var href = p.url || '#';
  var hasLink = href !== '#';
  var external = isExternal(href);
  var rel = external ? ' target="_blank" rel="noopener noreferrer"' : '';
  var tech = (p.technologies || []).map(chip).join('');
  var arrow = external ? icon('external') : '<span class="arrow" aria-hidden="true">→</span>';
  var cls = 'card project-card reveal';
  if (p.tier === 'flagship') cls += ' project-card--flagship';
  if (p.commercial) cls += ' commercial';

  var media =
    '<' + (hasLink ? 'a' : 'div') + ' class="project-media"' +
    (hasLink ? ' href="' + esc(href) + '"' + rel + ' tabindex="-1" aria-hidden="true"' : '') + '>' +
      '<img src="' + esc(ctx.asset(p.image)) + '" alt="' + esc(p.imageAlt || '') + '" loading="lazy" width="640" height="360">' +
      '<span class="project-type">' + esc(p.type || '') + '</span>' +
    '</' + (hasLink ? 'a' : 'div') + '>';

  var link = '';
  if (hasLink) {
    link = '<a class="project-link" href="' + esc(href) + '"' + rel + '>' +
      esc(p.urlLabel || ctx.labels.viewProject || 'View project') + arrow + '</a>';
  } else if (p.commercial && p.detailsHref) {
    link = '<p class="commercial-note"><a class="commercial-note-link" href="' + esc(p.detailsHref) + '">' +
      esc(p.detailsLabel || ctx.labels.commercialNote || 'Details available in Resume') +
      '<span class="arrow" aria-hidden="true">→</span></a></p>';
  } else if (p.commercial) {
    link = '<p class="commercial-note">' + esc(ctx.labels.commercialNote || 'Commercial project.') + '</p>';
  }

  return [
    '<article class="' + cls + '">',
    '  ' + media,
    '  <div class="project-body">',
    '    <div class="project-title-row">',
    '      <h3 class="project-title">' + esc(p.title) + '</h3>' +
      (p.status ? '<span class="status-badge' + (p.commercial ? ' commercial' : '') + '">' + esc(p.status) + '</span>' : ''),
    '    </div>',
    '    <p class="project-desc">' + esc(p.description) + '</p>',
    p.why ? '    <p class="project-why">' + esc(p.why) + '</p>' : null,
    tech ? '    <div class="project-tech">' + tech + '</div>' : null,
    '    ' + link,
    '  </div>',
    '</article>'
  ].filter(Boolean).join('\n');
}

