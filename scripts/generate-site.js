/* ---------- Replace the inner content of <tag id="..."> ... </tag> ---------- */
function replaceContainer(html, id, inner) {
  var openRe = new RegExp('<([a-zA-Z][a-zA-Z0-9]*)\\b[^>]*\\bid="' + id + '"[^>]*>');
  var m = openRe.exec(html);
  if (!m) throw new Error('Container #' + id + ' not found in HTML');
  var tag = m[1];
  var openEnd = m.index + m[0].length;

  var nextOpen = new RegExp('<' + tag + '\\b', 'g');
  var nextClose = new RegExp('</' + tag + '>', 'g');
  var depth = 1;
  var i = openEnd;
  nextOpen.lastIndex = i;
  nextClose.lastIndex = i;
  var closeEnd = -1;

  for (;;) {
    var o = nextOpen.exec(html);
    var c = nextClose.exec(html);
    if (!c) throw new Error('Unmatched container #' + id);
    if (o && o.index < c.index) {
      depth += 1;
      i = o.index + 1;
    } else {
      depth -= 1;
      if (depth === 0) { closeEnd = c.index; break; }
      i = c.index + 1;
    }
    nextOpen.lastIndex = i;
    nextClose.lastIndex = i;
  }

  // Keep the container's own closing tag: `after` starts at closeEnd.
  var before = html.slice(0, openEnd);
  var after = html.slice(closeEnd);
  return before + '\n' + inner + '\n' + after;
}

/* ---------- Fill one language page ---------- */
function fillPage(html, lang, content) {
  var ctx = {
    labels: content.labels || {},
    asset: function (src) { return lang === 'ru' ? '../' + String(src || '') : String(src || ''); },
    link: function (url) {
      var u = String(url || '');
      if (lang !== 'ru') return u;
      if (u.indexOf('http') === 0 || u.indexOf('#') === 0 || u.indexOf('mailto:') === 0) return u;
      return '../' + u;
    }
  };

  // Build marker (idempotent).
  if (html.indexOf('Generated by scripts/generate-site.js') === -1) {
    html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + BANNER);
  }

  // data/content.js is a build-time source only — browsers receive
  // pre-rendered HTML and do not need to download it.
  html = html.replace(/\n[ \t]*<script src="(?:\.\.\/)?data\/content\.js"><\/script>\n/g, '\n');

  var map = buildSectionMap(content, ctx);
  Object.keys(map).forEach(function (id) {
    html = replaceContainer(html, id, map[id]);
  });

  return html;
}

