/* --- Bootstrap redirect targets must resolve to real pages --- */
function extractBootPath(html) {
  const m = html.match(/location\.replace\('([^']+)'\s*\+\s*suffix\)/);
  return m ? m[1] : null;
}
const enBootTarget = extractBootPath(read('about/index.html'));
const ruBootTarget = extractBootPath(read('ru/about/index.html'));
const bootResolve = [
  {
    name: 'EN bootstrap target resolves to /ru/about/',
    pass: !!enBootTarget && new URL(enBootTarget, 'http://localhost:8080/about/').href === 'http://localhost:8080/ru/about/'
  },
  {
    name: 'RU bootstrap target resolves to /about/',
    pass: !!ruBootTarget && new URL(ruBootTarget, 'http://localhost:8080/ru/about/').href === 'http://localhost:8080/about/'
  }
];

const report = { en, ru, langBootstrap: langCases, bootResolve };
console.log(JSON.stringify(report, null, 2));

let pass = true;
['en', 'ru'].forEach((lang) => {
  Object.entries(report[lang]).forEach(([k, v]) => {
    if (k === 'relativeRefs') return;
    if (v === false || (Array.isArray(v) && v.length)) {
      pass = false;
      console.error('FAIL [' + lang + ']:', k, v);
    }
  });
});
langCases.forEach((c) => {
  if (!c.pass) { pass = false; console.error('FAIL [lang]:', c.name, c); }
});
bootResolve.forEach((b) => {
  if (!b.pass) { pass = false; console.error('FAIL [boot]:', b.name); }
});

if (!pass) process.exit(1);
console.log('\n✓ ALL ABOUT PRERENDER + LANGUAGE CHECKS PASSED (EN + RU)');
