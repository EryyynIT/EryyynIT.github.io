const report = { en, ru, langBootstrap: langCases };
console.log(JSON.stringify(report, null, 2));

let pass = true;
['en', 'ru'].forEach((lang) => {
  Object.entries(report[lang]).forEach(([k, v]) => {
    if (k === 'relativeRefs') return;
    if (v === false || (Array.isArray(v) && v.length)) {
      pass = false;
      console.error('FAIL [' + lang + ']:', k, v);
    }
  });
});
langCases.forEach((c) => {
  if (!c.pass) { pass = false; console.error('FAIL [lang]:', c.name, c); }
});

if (!pass) process.exit(1);
console.log('\n✓ ALL GAME PAGE PRERENDER + LANGUAGE CHECKS PASSED (EN + RU)');
